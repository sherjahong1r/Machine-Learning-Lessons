"""## Ushbu kod matnni xulosa qilish (summarization) vazifasini bajaradi. Ya'ni, uzun matndan (long_text o'zgaruvchisidagi matndan) uning asosiy g'oyasini qisqacha shaklda chiqarib beradi. Misolimizdagi sshleifer/distilbart-cnn-12-6 nomli model yordamida matn qisqartiriladi."""

from transformers import AutoTokenizer, AutoModelForSeq2SeqLM

# 1. Provide a long piece of text
long_text = "Hugging Face Transformers is an open-source library that provides thousands of pre-trained models to perform tasks on texts such as classification, information extraction, question answering, summarization, translation, text generation, and more. It supports interoperability between PyTorch, TensorFlow, and JAX frameworks. These models are highly optimized and can be used directly for inference, fine-tuned on custom datasets, or integrated into larger applications. The library is widely adopted in both research and industry due to its ease of use, robust features, and extensive community support. It democratizes access to state-of-the-art NLP models, enabling developers and researchers to build powerful language-aware applications with minimal effort."

# 2. Load the tokenizer and model for summarization
model_name = "sshleifer/distilbart-cnn-12-6"
tokenizer = AutoTokenizer.from_pretrained(model_name)
model = AutoModelForSeq2SeqLM.from_pretrained(model_name)

# 3. Tokenize the input text
inputs = tokenizer(long_text, max_length=1024, truncation=True, return_tensors="pt")

summary_ids = model.generate(
    inputs["input_ids"],
    max_length=100,
    min_length=30,
    do_sample=False
)

# 5. Decode the summary IDs back to text
summarized_text = tokenizer.decode(summary_ids[0], skip_special_tokens=True)

# 6. Print the summarized text
print(summarized_text)

