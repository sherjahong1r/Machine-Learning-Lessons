from transformers import AutoTokenizer, AutoModelForSeq2SeqLM

# 2. Initialize a translation pipeline for English to French by directly loading model and tokenizer
model_name = "Helsinki-NLP/opus-mt-en-fr"
tokenizer = AutoTokenizer.from_pretrained(model_name)
model = AutoModelForSeq2SeqLM.from_pretrained(model_name)

# 3. Define a sample English text to be translated
english_text = "Hello, how are you today? I hope you are having a good time."

# Tokenize the input text
inputs = tokenizer(english_text, return_tensors="pt")

# 4. Generate the translation
translated_ids = model.generate(**inputs)

# 5. Decode and print the translated text
translated_text = tokenizer.decode(translated_ids[0], skip_special_tokens=True)
print(translated_text)

